#!/usr/bin/env node
// build-katex-inline.cjs — genera lib/domain/slides/katex-inline.generated.ts
//
// Empaqueta KaTeX para uso 100% OFFLINE e idéntico en las TRES superficies de
// diapositiva (preview iframe `srcdoc`, export HTML standalone abierto por
// `file://`, y PDF vía Playwright `setContent`). Ninguna de ellas resuelve
// rutas relativas de forma fiable, así que la única opción robusta es INLINE:
//
//   - CSS de KaTeX con cada fuente woff2 embebida como data: base64.
//     Se eliminan las variantes woff/ttf (Chromium — el único motor en las
//     tres superficies — soporta woff2), reduciendo el payload a la mitad.
//   - katex.min.js + auto-render.min.js concatenados como un único string JS.
//
// Se emite como MÓDULO TS (strings), no lectura en runtime desde node_modules,
// para garantizar que los bytes sobreviven el trace del build standalone que
// va dentro del .exe.
//
// Idempotente: re-ejecutar regenera el mismo fichero. Se ejecuta en `prebuild`
// y bajo demanda con `node scripts/build-katex-inline.cjs`.

const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const KATEX_DIST = path.join(ROOT, "node_modules", "katex", "dist");
const OUT = path.join(
  ROOT,
  "lib",
  "domain",
  "slides",
  "katex-inline.generated.ts"
);

function fail(msg) {
  console.error(`\x1b[31m[katex-inline]\x1b[0m ${msg}`);
  process.exit(1);
}
function log(msg) {
  console.log(`\x1b[36m[katex-inline]\x1b[0m ${msg}`);
}

if (!fs.existsSync(KATEX_DIST)) {
  fail(`katex/dist not found at ${KATEX_DIST}. Run 'pnpm add katex' first.`);
}

// 1. CSS with woff2 fonts inlined as base64; strip woff/ttf sources.
let css = fs.readFileSync(path.join(KATEX_DIST, "katex.min.css"), "utf8");

// Inline every woff2 url(...) as a data URI.
const fontsDir = path.join(KATEX_DIST, "fonts");
let inlined = 0;
css = css.replace(/url\(fonts\/([^)]+?\.woff2)\)/g, (_m, file) => {
  const p = path.join(fontsDir, file);
  if (!fs.existsSync(p)) fail(`font missing: ${file}`);
  const b64 = fs.readFileSync(p).toString("base64");
  inlined++;
  return `url(data:font/woff2;base64,${b64})`;
});
if (inlined === 0) fail("no woff2 url() references found in katex.min.css");

// Remove the now-dangling woff and ttf sources from every @font-face src:
// `src:url(data:...woff2) format("woff2"),url(fonts/X.woff) format("woff"),url(fonts/X.ttf) format("truetype");`
// → keep only the woff2 data URI + its format().
css = css.replace(
  /,url\(fonts\/[^)]+?\.woff\)\s*format\("woff"\)/g,
  ""
);
css = css.replace(
  /,url\(fonts\/[^)]+?\.ttf\)\s*format\("truetype"\)/g,
  ""
);

// Safety: no remaining relative font references (all must be data URIs now).
if (/url\(fonts\//.test(css)) {
  fail("residual relative url(fonts/...) references remain in CSS");
}

// 2. JS: katex core + auto-render extension, concatenated.
const katexJs = fs.readFileSync(path.join(KATEX_DIST, "katex.min.js"), "utf8");
const autoRenderJs = fs.readFileSync(
  path.join(KATEX_DIST, "contrib", "auto-render.min.js"),
  "utf8"
);
const js = `${katexJs}\n${autoRenderJs}`;

// 3. Emit the TS module. Use a raw template literal with escaped backticks and
//    ${ so the embedded CSS/JS can't break out of the template.
function toTemplateLiteral(s) {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const katexVersion = require(
  path.join(ROOT, "node_modules", "katex", "package.json")
).version;

const out = `// AUTO-GENERATED by scripts/build-katex-inline.cjs — DO NOT EDIT BY HAND.
// KaTeX ${katexVersion} inlined for offline rendering (woff2 fonts as base64).
// Regenerate: node scripts/build-katex-inline.cjs
/* eslint-disable */

/** KaTeX CSS with all woff2 fonts embedded as base64 data URIs. */
export const KATEX_INLINE_CSS = \`${toTemplateLiteral(css)}\`;

/** katex.min.js + auto-render.min.js concatenated. */
export const KATEX_INLINE_JS = \`${toTemplateLiteral(js)}\`;

/** Version of KaTeX bundled. */
export const KATEX_INLINE_VERSION = ${JSON.stringify(katexVersion)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, "utf8");
const kb = Math.round(Buffer.byteLength(out) / 1024);
log(
  `wrote ${path.relative(ROOT, OUT)} (${kb} KB, ${inlined} woff2 fonts inlined, katex ${katexVersion})`
);
